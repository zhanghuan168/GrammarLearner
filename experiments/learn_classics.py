def learn_all_novels():
    """学习四大名著全部内容"""
    model = GrammarLearner()
    classics = load_classic_novels()

    total_texts = sum(len(v) for v in classics.values())
    print(f"📚 开始学习四大名著，共 {len(classics)} 部，{total_texts} 段文字")
    print("=" * 70)

    for novel_name, texts in classics.items():
        print(f"\n【{novel_name}】共 {len(texts)} 段")
        print("-" * 50)
        for i, text in enumerate(texts):
            print(f"  {i+1}. {text}")
            model.learn(text)
        print()

    return model


