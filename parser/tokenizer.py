    def tokenize(self, text):
        text = text.strip()
        if not text:
            return []

        tokens = []
        pattern = f"([{re.escape(self.punctuations)}])"
        parts = re.split(pattern, text)

        for part in parts:
            if not part:
                continue
            if re.match(f"^[{re.escape(self.punctuations)}]$", part):
                tokens.append(part)
            else:
                tokens.extend(self._mmcut(part))

        return tokens

    def _mmcut(self, text):
        result = []
        i = 0
        while i < len(text):
            matched = False
            for length in range(min(4, len(text) - i), 0, -1):
                word = text[i:i+length]
                if word in self.dict_set:
                    result.append(word)
                    i += length
                    matched = True
                    break
            if not matched:
                result.append(text[i])
                i += 1
        return result


