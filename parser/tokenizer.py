            # 三字词
            "西游记", "天宫", "龙宫", "地府", "西天", "取经",
            "唐僧", "师父", "徒弟", "师兄弟", "师徒",
            # 双字词
            "老师", "学生", "爸爸", "妈妈", "爷爷", "奶奶",
            "哥哥", "姐姐", "弟弟", "妹妹", "儿子", "女儿",
            "学校", "教室", "书本", "电脑", "手机", "电视",
            "中国", "北京", "天空", "太阳", "月亮", "星星",
            "汽车", "火车", "飞机", "轮船", "自行车",
            "衣服", "裤子", "鞋子", "帽子", "袜子",
            "眼睛", "耳朵", "鼻子", "嘴巴", "小手",
            "今天", "明天", "昨天", "早上", "中午", "晚上",
            "现在", "以前", "以后", "喜欢", "讨厌",
            "漂亮", "美丽", "可爱", "聪明", "勇敢", "善良",
            "厉害", "安静", "热闹", "干净", "年轻",
            "非常", "特别", "已经", "将要", "一定",
            "因为", "所以", "如果", "但是", "虽然",
            # 单字词（名词）
            "猫", "狗", "鸟", "鱼", "虫", "花", "草", "树", "山", "水",
            "河", "海", "湖", "天", "地", "人", "子", "父", "母",
            "书", "笔", "纸", "门", "窗", "桌", "椅", "床",
            "菜", "肉", "米", "面", "糖", "瓜", "果",
            # 单字词（动/形）
            "是", "有", "会", "能", "可", "要", "想", "去", "来", "在",
            "看", "读", "写", "做", "吃", "喝", "玩", "睡", "学", "工作",
